#!/usr/bin/env python3
"""Render a default-deny egress policy from the Server MCP configs.

The proxy policy is host-owned and mounted read-only. This script derives the
allow rules from the same YAML files the MCP services use, so the network
boundary and the tool configuration cannot drift silently.

Usage:
    uv run --frozen --no-dev --all-packages python deploy/render-egress-policy.py \
        --remote ~/.config/server-mcp/remote.yaml \
        --disk ~/.config/server-mcp/disk.yaml \
        --output ~/.config/server-mcp/egress-policy.conf
"""

from __future__ import annotations

import argparse
import ipaddress
from pathlib import Path
from typing import Any

import yaml


def _load(path: Path) -> dict[str, Any]:
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
    except OSError as exc:
        raise SystemExit(f"cannot read {path}: {exc}") from exc
    except yaml.YAMLError as exc:
        raise SystemExit(f"invalid YAML in {path}: {exc}") from exc
    if data is None:
        return {}
    if not isinstance(data, dict):
        raise SystemExit(f"{path} must contain a YAML mapping")
    return data


def _target(value: Any, name: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise SystemExit(f"{name} must be a non-empty hostname or IP address")
    host = value.strip()
    if any(char.isspace() for char in host):
        raise SystemExit(f"{name} contains whitespace: {host!r}")
    return host


def _port(value: Any, name: str, default: int) -> int:
    if value is None:
        return default
    try:
        port = int(value)
    except (TypeError, ValueError) as exc:
        raise SystemExit(f"{name} must be an integer") from exc
    if not 1 <= port <= 65535:
        raise SystemExit(f"{name} is out of range: {port}")
    return port


def _rule(host: str, port: int) -> str:
    try:
        ip = ipaddress.ip_address(host)
    except ValueError:
        return f"allow {host} {port}"
    if ip.version == 6:
        return f"allow [{ip}] {port}"
    return f"allow {ip} {port}"


def _collect(config: dict[str, Any], label: str) -> list[str]:
    rules: list[str] = []
    ssh = config.get("ssh") or {}
    if isinstance(ssh, dict) and ssh.get("host"):
        host = _target(ssh.get("host"), f"{label}.ssh.host")
        port = _port(ssh.get("port"), f"{label}.ssh.port", 22)
        rules.append(_rule(host, port))

    for section, default_port in (("influxdb", 8181), ("prometheus", 9090)):
        value = config.get(section) or {}
        if not isinstance(value, dict) or not value.get("enabled"):
            continue
        host = _target(value.get("host"), f"{label}.{section}.host")
        port = _port(value.get("port"), f"{label}.{section}.port", default_port)
        rules.append(_rule(host, port))
    return rules


def render(remote: dict[str, Any], disk: dict[str, Any]) -> str:
    rules = _collect(remote, "remote") + _collect(disk, "disk")
    # Preserve order but drop duplicates from the two configs.
    unique = list(dict.fromkeys(rules))
    lines = [
        "# Generated by deploy/render-egress-policy.py. Do not edit by hand;",
        "# edit the source configs and re-run the installer or this script.",
        "#",
        "# The MCP containers have no direct route out. mcp-egress-proxy applies",
        "# this default-deny policy. Hostname rules also match subdomains.",
        "",
        "default deny",
        "",
    ]
    lines.extend(unique)
    if not unique:
        lines.append("# No SSH or metric destinations were enabled in the configs.")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--remote", type=Path, required=True)
    parser.add_argument("--disk", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args(argv)

    text = render(_load(args.remote), _load(args.disk))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding="utf-8")
    args.output.chmod(0o600)
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
